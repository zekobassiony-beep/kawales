-- يُشغَّل مرة واحدة على مشروع Supabase (SQL Editor أو psql).
-- الغرض: تسجيل **وقت** حضور كل تذكرة على السيرفر، لا الحالة فقط،
--        حتى يظهر تنبيه «مستخدمة مسبقًا في الساعة …» في ماسح البوابة.
--
-- ملاحظة: الكود يتدرّج بأمان إن لم يُشغَّل هذا الترحيل (يُسجَّل وقت الحضور
-- في التخزين المحلي للجهاز فقط) — لكن تشغيله مطلوب لماسح حقيقي على السيرفر.
-- ============================================================

alter table public.tickets
  add column if not exists checked_in_at timestamptz;

comment on column public.tickets.checked_in_at is
  'وقت تسجيل الحضور عند بوابة المسرح (يُملأ مرة واحدة عند أول مسح ناجح).';

-- فهرس مساعد لتقارير الحضور لكل عرض.
create index if not exists tickets_checked_in_at_idx
  on public.tickets (checked_in_at)
  where checked_in_at is not null;

